import fs from 'node:fs';

const patch = (path, transform) => {
  const before = fs.readFileSync(path, 'utf8');
  const after = transform(before);
  if (after !== before) {
    fs.writeFileSync(path, after);
    console.log(`✓ Claridad financiera V2 segura: ${path}`);
  }
};

patch('types.ts', source => {
  if (!source.includes("'saco_beneficencia' | 'cuota_regular' | 'cuota_extra'")) {
    source = source.replace(
      "'saco_beneficencia' | 'cuota_extra' | 'evento'",
      "'saco_beneficencia' | 'cuota_regular' | 'cuota_extra' | 'evento'"
    );
  }

  if (!source.includes("quotaType?: 'regular' | 'extra' | 'unclassified' | 'manual';")) {
    source = source.replace(
      'export interface TreasuryEntry { id: string;',
      "export interface TreasuryEntry { id: string; quotaType?: 'regular' | 'extra' | 'unclassified' | 'manual'; quotaConcept?: string; period?: string; memberId?: string; memberName?: string; receiptUrls?: string[]; receiptIds?: string[];"
    );
  }
  return source;
});

